"""Regenerates rust/parity/parity.md from core's Vitest test list, merging statuses from rust/parity/status/*.tsv.

Usage: python3 rust/scripts/gen-parity.py [--core <dir>] [--refresh [<test file>...]]
--core is the core checkout whose tests are listed (default: the megarepo pin, repos/livestore).
--refresh re-collects the test list (slow) with <core>/node_modules/.bin/vitest, so it needs a core
checkout with its own install; with file paths only those files are re-collected.
wa-sqlite's own `*.test.js` suites run on web-test-runner (jasmine), not Vitest: their `it(...)` names are read
from the file and the `./*.js` spec modules it imports.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from itertools import takewhile
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
OUT = BASE / "parity/parity.md"
STATUS_DIR = BASE / "parity/status"
CACHE = BASE / "parity/vitest-list.json"
CORE = Path(sys.argv[sys.argv.index("--core") + 1]).resolve() if "--core" in sys.argv else BASE.parent / "repos/livestore"
ROOT = str(CORE) + "/"

IN_SCOPE = [
    ("Sync + storage", r"^(packages/@livestore/common/src/(sync|leader-thread)/|tests/package-common/src/(leader-thread/|[^/]+\.test)|tests/sync-provider/src/|packages/@livestore/sync-cf/src/client/|packages/@livestore/common/src/schema/(EventSequenceNumber|LiveStoreEvent))"),
    ("Schema + queries", r"^packages/@livestore/common/src/(schema|schema-management)/"),
    ("Store + reactivity", r"^(packages/@livestore/livestore/src/|tests/package-common/src/client-session/)"),
    ("SQLite", r"^(tests/wa-sqlite/test/unit/|packages/@livestore/wa-sqlite/test/)"),
]


def main() -> None:
    files = in_scope_files()
    cached: dict[str, list[str]] = json.loads(CACHE.read_text()) if CACHE.exists() else {}
    if "--refresh" in sys.argv or not CACHE.exists():
        only = list(takewhile(lambda a: not a.startswith("--"), sys.argv[sys.argv.index("--refresh") + 1 :])) if "--refresh" in sys.argv else []
        cached.update(collect(only or files))
        CACHE.write_text(json.dumps(cached, indent=1))
    tests = cached
    statuses = load_statuses()

    core_rev = subprocess.run(["git", "rev-parse", "HEAD"], cwd=CORE, capture_output=True, text=True, check=True).stdout.strip()
    lines = [
        "# Rust client test parity",
        "",
        "Generated by `rust/scripts/gen-parity.py`; edit `rust/parity/status/*.tsv`, not this file.",
        f"Core commit: `{core_rev}`. Parity baseline: `06b50576509984475cca71bea8ea3f243c7650d1`.",
        "Source: `vitest list` per file. Status: `todo` | `ported: <rust test>` | `n/a: <reason>`.",
        "Parity is claimed only when no row says `todo`.",
        "",
    ]
    used: set[str] = set()
    total = todo = 0
    for title, _ in IN_SCOPE:
        lines += [f"## {title}", ""]
        for f in files:
            if section(f) != title:
                continue
            lines += [f"### `{f}`", "", "| Test | Status |", "|---|---|"]
            for name in tests.get(f, []):
                key = f"{f} :: {name}"
                status = statuses.get(key, "todo")
                used.add(key)
                total += 1
                todo += status == "todo"
                lines.append(f"| {key} | {status} |")
            lines.append("")
    stale = sorted(set(statuses) - used)
    if stale:
        lines += ["## Status rows that match no real test", "", *[f"- {k}" for k in stale], ""]
    lines.append(f"In-scope tests: {total}. Still todo: {todo}. Stale status rows: {len(stale)}.")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"tests {total}, todo {todo}, stale {len(stale)}")


def in_scope_files() -> list[str]:
    out = subprocess.run(["git", "ls-files", "*.test.ts", "*.test.tsx", "*.test.js"], cwd=CORE, capture_output=True, text=True, check=True).stdout
    return [f for f in out.split() if section(f) and "intent-layer" not in f]


def section(path: str) -> str | None:
    return next((title for title, rx in IN_SCOPE if re.search(rx, path)), None)


def collect(files: list[str]) -> dict[str, list[str]]:
    """`--json=<file>` must name a separate output file; a bare `--json <path>` overwrites <path>."""
    tmp = BASE / "target/vitest-list.json"
    tmp.parent.mkdir(parents=True, exist_ok=True)
    result: dict[str, list[str]] = {}
    for f in files:
        if f.endswith(".js"):
            result[f] = jasmine_names(CORE / f)
            print(f"{len(result[f]):4} {f}", file=sys.stderr)
            continue
        tmp.unlink(missing_ok=True)
        subprocess.run([str(CORE / "node_modules/.bin/vitest"), "list", f"--json={tmp}", f], cwd=CORE, capture_output=True, timeout=300)
        names: list[str] = []
        for t in json.loads(tmp.read_text()) if tmp.exists() else []:
            name = " ".join(t["name"].split(" > ")[-1].split()).replace("|", "/")
            if t["file"].replace(ROOT, "") == f and name not in names:
                names.append(name)
        result[f] = names
        print(f"{len(names):4} {f}", file=sys.stderr)
    return result


def jasmine_names(path: Path) -> list[str]:
    """`it('...')` names in a jasmine spec file and the local spec modules it imports, deduplicated."""
    sources = [path] + [path.parent / m for m in re.findall(r"from '\./(\w+\.js)'", path.read_text()) if m != "TestContext.js"]
    names: list[str] = []
    for src in sources:
        for name in re.findall(r"\bit\('([^']+)'", src.read_text()):
            if name not in names:
                names.append(name)
    return names


def load_statuses() -> dict[str, str]:
    statuses: dict[str, str] = {}
    for p in sorted(STATUS_DIR.glob("*.tsv")):
        for line in p.read_text().splitlines():
            if "\t" in line:
                key, status = line.split("\t", 1)
                statuses[" ".join(key.split())] = status.strip()
    return statuses


if __name__ == "__main__":
    main()
