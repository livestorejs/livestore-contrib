//! Port of tests/wa-sqlite/test/unit/serialize-deserialize.test.ts (`importDb` = deserialize into a temp DB + backup).
use std::{path::PathBuf, process::Command, sync::OnceLock, time::Duration, time::Instant};

use rusqlite::{Connection, backup::Backup};

const NORTHWIND_URL: &str =
    "https://github.com/jpwhite3/northwind-SQLite3/raw/refs/heads/main/dist/northwind.db";

/// `beforeAll` fetch of the Northwind DB, cached under the target dir.
fn northwind() -> &'static [u8] {
    static DATA: OnceLock<Vec<u8>> = OnceLock::new();
    DATA.get_or_init(|| {
        let path = PathBuf::from(env!("CARGO_TARGET_TMPDIR")).join("northwind.db");
        if !path.exists() {
            let tmp = path.with_extension("part");
            let ok = Command::new("curl")
                .args(["-LsSf", "-o"])
                .arg(&tmp)
                .arg(NORTHWIND_URL)
                .status()
                .unwrap()
                .success();
            assert!(ok, "download {NORTHWIND_URL}");
            std::fs::rename(&tmp, &path).unwrap();
        }
        std::fs::read(path).unwrap()
    })
}

fn import_db(db: &mut Connection, source: &[u8]) {
    let mut tmp = Connection::open_in_memory().unwrap();
    tmp.deserialize_read_exact("main", source, source.len(), false)
        .unwrap();
    Backup::new(&tmp, db)
        .unwrap()
        .run_to_completion(i32::MAX, Duration::ZERO, None)
        .unwrap();
}

fn export_db(db: &Connection) -> Vec<u8> {
    db.serialize("main").unwrap().to_vec()
}

fn tables(db: &Connection) -> usize {
    db.prepare("SELECT name FROM sqlite_master WHERE type='table'")
        .unwrap()
        .query_map([], |_| Ok(()))
        .unwrap()
        .count()
}

fn check_export_header(exported: &[u8]) -> bool {
    exported[0] == 0x53
}

#[test]
fn should_handle_single_export_correctly_baseline() {
    let data = northwind().to_vec();
    let mut db1 = Connection::open_in_memory().unwrap();
    import_db(&mut db1, &data);
    assert!(check_export_header(&export_db(&db1)));
    drop(db1);

    let mut db2 = Connection::open_in_memory().unwrap();
    import_db(&mut db2, &data);
    assert_eq!(tables(&db2), 14);
    assert!(check_export_header(&export_db(&db2)));
}

#[test]
fn should_fix_corruption_with_2_exports_on_first_database() {
    let data = northwind().to_vec();
    let mut db1 = Connection::open_in_memory().unwrap();
    import_db(&mut db1, &data);
    assert!(check_export_header(&export_db(&db1)));
    assert!(check_export_header(&export_db(&db1)));
    drop(db1);

    let mut db2 = Connection::open_in_memory().unwrap();
    import_db(&mut db2, &data);
    let exported = export_db(&db2);
    let first_bytes = exported[..16]
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect::<Vec<_>>()
        .join(" ");
    assert_eq!(tables(&db2), 14);
    assert!(check_export_header(&exported));
    assert_eq!(
        first_bytes,
        "53 51 4c 69 74 65 20 66 6f 72 6d 61 74 20 33 00"
    );
    assert_ne!(
        first_bytes,
        "00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00"
    );
}

#[test]
fn should_handle_reasonable_numbers_of_sequential_exports() {
    let data = northwind().to_vec();
    let mut db1 = Connection::open_in_memory().unwrap();
    import_db(&mut db1, &data);
    assert!(check_export_header(&export_db(&db1)));
    assert!(check_export_header(&export_db(&db1)));
    drop(db1);

    let mut db2 = Connection::open_in_memory().unwrap();
    import_db(&mut db2, &data);
    assert_eq!(tables(&db2), 14);
    assert!(check_export_header(&export_db(&db2)));
}

#[test]
fn should_prevent_memory_leaks_with_immediate_buffer_cleanup() {
    let mut db = Connection::open_in_memory().unwrap();
    import_db(&mut db, northwind());
    for _ in 0..10 {
        let exported = export_db(&db);
        assert!(check_export_header(&exported));
        assert!(exported.len() > 1_000_000);
    }
}

#[test]
fn should_maintain_data_integrity_across_exports() {
    let mut db = Connection::open_in_memory().unwrap();
    import_db(&mut db, northwind());
    let export1 = export_db(&db);
    let tables1 = tables(&db);
    let export2 = export_db(&db);
    let tables2 = tables(&db);

    assert!(check_export_header(&export1));
    assert!(check_export_header(&export2));
    assert_eq!(export1.len(), export2.len());
    assert_eq!(tables1, tables2);
    assert_eq!(tables1, 14);
    assert_eq!(export1[..16], export2[..16]);
}

#[test]
fn should_handle_large_database_500mb_import_export_with_timing() {
    // Same fixture and skip rule as TS: generated by `bun ./test/setup/database-setup.ts` in tests/wa-sqlite.
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../../repos/livestore/tests/wa-sqlite/test/fixtures/large_test.db");
    let Ok(large) = std::fs::read(&path) else {
        eprintln!("Large test database not found, skipping test");
        return;
    };
    let mut db = Connection::open_in_memory().unwrap();

    let import_start = Instant::now();
    import_db(&mut db, &large);
    let import_time = import_start.elapsed();

    assert!(tables(&db) > 0);
    let count = |table: &str| {
        db.query_row(&format!("SELECT COUNT(*) FROM {table}"), [], |r| {
            r.get::<_, i64>(0)
        })
        .unwrap()
    };
    assert!(count("users") > 0);
    assert!(count("posts") > 0);
    assert!(count("comments") > 0);

    let export_start = Instant::now();
    let exported = export_db(&db);
    let export_time = export_start.elapsed();

    assert!(check_export_header(&exported));
    assert!(exported.len() > 500 * 1024 * 1024);
    assert!(import_time < Duration::from_secs(30));
    assert!(export_time < Duration::from_secs(30));
}
